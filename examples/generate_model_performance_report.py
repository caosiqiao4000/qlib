import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

import matplotlib
matplotlib.use("Agg")

import os
import pickle
import pandas as pd

import qlib
from qlib.constant import REG_CN
from qlib.utils import init_instance_by_config
from qlib.contrib.report.analysis_model import model_performance_graph


def main():
    output_dir = Path(__file__).parent / "model_performance_report"
    output_dir.mkdir(exist_ok=True)

    provider_uri = os.path.expanduser("~/.qlib/qlib_data/cn_data")
    qlib.init(provider_uri=provider_uri, region=REG_CN)

    market = "csi300"
    data_handler_config = {
        "start_time": "2008-01-01",
        "end_time": "2020-08-01",
        "fit_start_time": "2008-01-01",
        "fit_end_time": "2014-12-31",
        "instruments": market,
    }

    dataset_config = {
        "class": "DatasetH",
        "module_path": "qlib.data.dataset",
        "kwargs": {
            "handler": {
                "class": "Alpha158",
                "module_path": "qlib.contrib.data.handler",
                "kwargs": data_handler_config,
            },
            "segments": {
                "train": ("2008-01-01", "2014-12-31"),
                "valid": ("2015-01-01", "2016-12-31"),
                "test": ("2017-01-01", "2020-08-01"),
            },
        },
    }
    dataset = init_instance_by_config(dataset_config)

    mlruns_dir = Path(__file__).parent / "mlruns"

    pred_pkl_files = sorted(mlruns_dir.rglob("pred.pkl"), key=lambda p: p.stat().st_mtime, reverse=True)

    if not pred_pkl_files:
        raise FileNotFoundError("No pred.pkl found in mlruns directory. Run the notebook first.")

    pred_pkl_path = pred_pkl_files[0]
    print(f"Using pred.pkl from: {pred_pkl_path}")

    with open(pred_pkl_path, "rb") as f:
        pred_df = pickle.load(f)

    label_df = dataset.prepare("test", col_set="label")
    label_df.columns = ["label"]

    pred_label = pd.concat([label_df, pred_df], axis=1, sort=True).reindex(label_df.index)

    print(f"pred_label shape: {pred_label.shape}")
    print(f"pred_label head:\n{pred_label.head()}")

    figure_list = model_performance_graph(
        pred_label,
        show_notebook=False,
        graph_names=["group_return", "pred_ic", "pred_autocorr", "pred_turnover"],
    )

    graph_name_map = {
        0: "01_group_cumulative_return",
        1: "02_group_distribution",
        2: "03_ic_bar",
        3: "04_monthly_ic_heatmap",
        4: "05_ic_histogram_qq",
        5: "06_autocorrelation",
        6: "07_turnover",
    }

    for i, fig in enumerate(figure_list):
        name = graph_name_map.get(i, f"figure_{i:02d}")
        fig.write_image(output_dir / f"{name}.png", width=1200, height=600, scale=2)
        print(f"Saved: {name}.png")

    sections = [
        ("01_group_cumulative_return", "Group Cumulative Return",
         "Cumulative return by group (Group 1 = highest score, Group 5 = lowest score). "
         "A good model should show clear separation between groups, with Group 1 consistently outperforming Group 5."),
        ("02_group_distribution", "Long-Short / Long-Average Distribution",
         "Distribution of daily long-short returns (Group 1 - Group 5) and long-average returns "
         "(Group 1 - market average). A good model should have a positive mean for both distributions."),
        ("03_ic_bar", "IC (Information Coefficient)",
         "Daily IC values over time. IC measures the cross-sectional Pearson correlation between "
         "predicted scores and actual returns. Higher and more consistent IC indicates better predictive power."),
        ("04_monthly_ic_heatmap", "Monthly IC Heatmap",
         "Monthly average IC values. This shows whether the model's predictive power is consistent "
         "across different months and years."),
        ("05_ic_histogram_qq", "IC Distribution & Q-Q Plot",
         "Histogram of IC values and Q-Q plot against normal distribution. "
         "A good model should have IC centered above zero with a roughly normal distribution."),
        ("06_autocorrelation", "Prediction Autocorrelation",
         "Autocorrelation of prediction scores at lag 1. Lower autocorrelation is generally better, "
         "indicating the model is updating its predictions with new information rather than repeating old predictions."),
        ("07_turnover", "Top-Bottom Turnover",
         "Turnover rate of top and bottom groups. This measures how much the composition of the "
         "top/bottom groups changes day-to-day. Higher turnover means the model is more dynamic."),
    ]

    md_lines = []
    md_lines.append("# Model Performance Report\n")
    md_lines.append(
        "This report is generated by `analysis_model.model_performance_graph(pred_label)` from Qlib.\n"
    )
    md_lines.append(f"**Data source**: `pred.pkl` from MLflow run at `{pred_pkl_path.parent.parent.name}`\n")
    md_lines.append(f"**pred_label shape**: {pred_label.shape[0]} rows x {pred_label.shape[1]} columns\n")
    md_lines.append("## Function Overview\n")
    md_lines.append(
        "`model_performance_graph` is a comprehensive model evaluation function in Qlib that "
        "generates multiple diagnostic charts to assess the quality of a predictive model for "
        "financial time series.\n"
    )
    md_lines.append("### Parameters\n")
    md_lines.append("| Parameter | Description |\n")
    md_lines.append("|---|---|\n")
    md_lines.append(
        "| `pred_label` | DataFrame with MultiIndex `[instrument, datetime]`, columns `score` and `label` |\n"
    )
    md_lines.append("| `lag` | Lag for autocorrelation computation (default: 1) |\n")
    md_lines.append("| `N` | Number of groups for cumulative return (default: 5) |\n")
    md_lines.append("| `reverse` | If True, reverse score direction |\n")
    md_lines.append("| `rank` | If True, use Rank IC (Spearman) instead of Pearson |\n")
    md_lines.append("| `graph_names` | List of graph types to generate |\n")
    md_lines.append("| `show_notebook` | Whether to display in notebook (default: True) |\n")
    md_lines.append("| `show_nature_day` | Whether to show non-trading days on x-axis |\n")

    md_lines.append("\n## Generated Charts\n")

    for fname, title, desc in sections:
        md_lines.append(f"### {title}\n")
        md_lines.append(f"![{title}](model_performance_report/{fname}.png)\n")
        md_lines.append(f"{desc}\n")

    md_lines.append("\n## Usage Example\n")
    md_lines.append("```python\n")
    md_lines.append("from qlib.contrib.report.analysis_model import model_performance_graph\n")
    md_lines.append("\n")
    md_lines.append("figure_list = model_performance_graph(\n")
    md_lines.append("    pred_label,\n")
    md_lines.append("    show_notebook=False,\n")
    md_lines.append("    graph_names=['group_return', 'pred_ic', 'pred_autocorr', 'pred_turnover'],\n")
    md_lines.append(")\n")
    md_lines.append("\n")
    md_lines.append("for i, fig in enumerate(figure_list):\n")
    md_lines.append("    fig.write_image(f'figure_{i}.png', width=1200, height=600, scale=2)\n")
    md_lines.append("```\n")

    report_path = Path(__file__).parent / "model_performance_report.md"
    report_path.write_text("\n".join(md_lines), encoding="utf-8")
    print(f"\nReport saved to: {report_path}")


if __name__ == "__main__":
    main()